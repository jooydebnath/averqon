#!/usr/bin/env bash
# Averqon installer for Debian/Ubuntu and RHEL-family (Fedora, RHEL, Rocky, Alma) systems.
#
#   sudo ./scripts/install.sh [--dry-run] [--admin-ip IP[/CIDR]]... [--ssh-port N]... [--enable] [--no-dashboard]
#
# Safety: the installer records your current SSH client address and the sshd port(s) as
# protected management access BEFORE anything can be enforced, and it never starts the
# firewall unless you pass --enable.
set -euo pipefail

PREFIX=/opt/averqon
CONF=/etc/averqon
STATE=/var/lib/averqon
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DRY=0; ENABLE=0; DASH=1
ADMIN_IPS=(); SSH_PORTS=()

log()  { printf '[averqon-install] %s\n' "$*"; }
die()  { printf '[averqon-install] ERROR: %s\n' "$*" >&2; exit 1; }
run()  { if [ "$DRY" = 1 ]; then printf '  (dry-run) %s\n' "$*"; else "$@"; fi; }

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1;;
    --enable) ENABLE=1;;
    --no-dashboard) DASH=0;;
    --admin-ip) shift; ADMIN_IPS+=("${1:?--admin-ip needs a value}");;
    --ssh-port) shift; SSH_PORTS+=("${1:?--ssh-port needs a value}");;
    -h|--help) sed -n '2,10p' "$0"; exit 0;;
    *) die "unknown option: $1";;
  esac
  shift
done
[ "$(id -u)" -eq 0 ] || [ "$DRY" = 1 ] || die "run as root (or use --dry-run)"

# ---- validate operator-supplied values (they end up in a config file)
for ip in "${ADMIN_IPS[@]:-}"; do
  [ -z "$ip" ] || [[ "$ip" =~ ^[0-9a-fA-F:.]+(/[0-9]{1,3})?$ ]] || die "invalid --admin-ip: $ip"
done
for p in "${SSH_PORTS[@]:-}"; do
  [ -z "$p" ] || { [[ "$p" =~ ^[0-9]{1,5}$ ]] && [ "$p" -ge 1 ] && [ "$p" -le 65535 ]; } || die "invalid --ssh-port: $p"
done

# ---- distribution detection (never assume all distros behave alike)
. /etc/os-release 2>/dev/null || die "cannot read /etc/os-release"
FAMILY=unknown
case " ${ID:-} ${ID_LIKE:-} " in
  *" debian "*|*" ubuntu "*) FAMILY=debian;;
  *" rhel "*|*" fedora "*|*" centos "*) FAMILY=rhel;;
esac
[ "$FAMILY" != unknown ] || die "unsupported distribution: ${PRETTY_NAME:-$ID}"
log "detected ${PRETTY_NAME:-$ID} (family: $FAMILY), kernel $(uname -r)"

# ---- Python >= 3.12
PY=""
for c in python3.13 python3.12 python3; do
  if command -v "$c" >/dev/null 2>&1 && "$c" -c 'import sys; sys.exit(0 if sys.version_info >= (3,12) else 1)'; then PY="$c"; break; fi
done
install_pkgs() {
  if [ "$FAMILY" = debian ]; then
    run env DEBIAN_FRONTEND=noninteractive apt-get update -y
    run env DEBIAN_FRONTEND=noninteractive apt-get install -y "$@"
  else
    run "$(command -v dnf || command -v yum)" install -y "$@"
  fi
}
if [ -z "$PY" ]; then
  log "Python 3.12+ not found; trying the distribution package"
  if [ "$FAMILY" = debian ]; then install_pkgs python3.12 python3.12-venv || true; else install_pkgs python3.12 || true; fi
  command -v python3.12 >/dev/null 2>&1 && PY=python3.12
fi
[ -n "$PY" ] || [ "$DRY" = 1 ] || die "Python 3.12+ is required and was not available from your distribution. Install it (e.g. from deadsnakes, uv, or pyenv) and re-run."
[ -n "$PY" ] || PY=python3.12
if [ "$FAMILY" = debian ]; then install_pkgs python3-venv nftables iptables || true; else install_pkgs nftables iptables || true; fi
command -v nft >/dev/null 2>&1 || command -v iptables >/dev/null 2>&1 || [ "$DRY" = 1 ] || die "neither nft nor iptables is available"

# ---- management access detection (anti-lockout)
if [ ${#SSH_PORTS[@]} -eq 0 ]; then
  if command -v sshd >/dev/null 2>&1; then
    while read -r p; do SSH_PORTS+=("$p"); done < <(sshd -T 2>/dev/null | awk '$1=="port"{print $2}')
  fi
  [ ${#SSH_PORTS[@]} -gt 0 ] || SSH_PORTS=(22)
fi
if [ -n "${SSH_CONNECTION:-}" ]; then
  CLIENT_IP="${SSH_CONNECTION%% *}"
  ADMIN_IPS+=("$CLIENT_IP"); log "protecting your current SSH client address: $CLIENT_IP"
fi
[ ${#ADMIN_IPS[@]} -gt 0 ] || log "WARNING: no admin IP known. Pass --admin-ip so you cannot be banned or rate-limited."
log "protected SSH port(s): ${SSH_PORTS[*]}"

# ---- users, directories
getent group averqon >/dev/null || run groupadd --system averqon
id -u averqon >/dev/null 2>&1 || run useradd --system --gid averqon --home-dir "$STATE" --shell /usr/sbin/nologin averqon
run install -d -m 0750 -o root -g averqon "$CONF"
run install -d -m 0750 -o averqon -g averqon "$STATE"
run install -d -m 0755 "$PREFIX"

# ---- application
run "$PY" -m venv "$PREFIX/venv"
run "$PREFIX/venv/bin/pip" install --upgrade pip
run "$PREFIX/venv/bin/pip" install "$SRC"
run install -d -m 0755 "$PREFIX/docs"
run cp -r "$SRC/docs/." "$PREFIX/docs/"
run install -m 0644 "$SRC/deploy/sysctl/99-averqon.conf" /etc/sysctl.d/99-averqon.conf

# ---- configuration (never overwrite an existing config)
if [ ! -f "$CONF/averqon.yaml" ]; then
  if [ "$DRY" = 1 ]; then log "(dry-run) would write $CONF/averqon.yaml"; else
    {
      echo "# Generated by install.sh. Secrets live in $CONF/averqon.env, not here."
      echo "environment: production"
      echo "database:"; echo "  url: sqlite:///$STATE/averqon.db"
      echo "firewall:"; echo "  backend: auto"; echo "  management_ports: [$(IFS=,; echo "${SSH_PORTS[*]}")]"
      echo "  backup_dir: $STATE/backups"; echo "  blocklist_dir: $STATE/blocklists"
      echo "  admin_ips:"; for ip in "${ADMIN_IPS[@]:-}"; do [ -z "$ip" ] || echo "    - \"$ip\""; done
      [ ${#ADMIN_IPS[@]} -gt 0 ] || echo "    []"
      echo "api:"; echo "  host: 127.0.0.1"; echo "  port: 8443"; echo "  executor_socket: /run/averqon/executor.sock"
      echo "  allowed_uids: [$(id -u averqon 2>/dev/null || echo 0)]"
    } > "$CONF/averqon.yaml"
    chown root:averqon "$CONF/averqon.yaml"; chmod 0640 "$CONF/averqon.yaml"
  fi
fi
if [ ! -f "$CONF/averqon.env" ]; then
  if [ "$DRY" = 1 ]; then log "(dry-run) would write $CONF/averqon.env with a generated secret"; else
    ( umask 077; printf 'AVERQON_SECRET_KEY=%s\n' "$("$PY" -c 'import secrets; print(secrets.token_urlsafe(48))')" > "$CONF/averqon.env" )
    chown root:root "$CONF/averqon.env"; chmod 0600 "$CONF/averqon.env"
  fi
fi

# ---- database + dashboard + units
run "$PREFIX/venv/bin/averqon" init-db --config "$CONF/averqon.yaml"
if [ "$DASH" = 1 ] && command -v npm >/dev/null 2>&1; then
  log "building dashboard"
  run bash -c "cd '$SRC/dashboard' && npm ci --no-audit --no-fund && npm run build"
  run rm -rf "$PREFIX/dashboard"; run install -d "$PREFIX/dashboard"
  run cp -r "$SRC/dashboard/.next/standalone/." "$PREFIX/dashboard/"
  run install -d "$PREFIX/dashboard/.next"; run cp -r "$SRC/dashboard/.next/static" "$PREFIX/dashboard/.next/static"
else
  log "dashboard not installed (npm missing or --no-dashboard); the API and CLI work without it"
fi
for u in executor api daemon dashboard; do run install -m 0644 "$SRC/deploy/systemd/averqon-$u.service" "/etc/systemd/system/averqon-$u.service"; done
run install -m 0755 "$SRC/scripts/averqon-emergency-disable.sh" /usr/local/sbin/averqon-emergency-disable
run ln -sf "$PREFIX/venv/bin/averqon" /usr/local/bin/averqon
run systemctl daemon-reload

if [ "$ENABLE" = 1 ]; then
  [ ${#ADMIN_IPS[@]} -gt 0 ] || die "--enable requires at least one admin IP (--admin-ip) to avoid lockout"
  run sysctl --system >/dev/null
  run systemctl enable --now averqon-executor averqon-api averqon-daemon
  [ -d "$PREFIX/dashboard" ] && run systemctl enable --now averqon-dashboard
  log "services started. If you lose access, use the console and run: averqon-emergency-disable"
else
  log "installed but NOT started. Create an admin:  AVERQON_PASSWORD='...' averqon user create admin --role admin --config $CONF/averqon.yaml"
  log "review $CONF/averqon.yaml, then: systemctl enable --now averqon-executor averqon-api averqon-daemon"
fi
